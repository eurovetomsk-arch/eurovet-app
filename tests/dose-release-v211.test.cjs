const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),rd=f=>fs.readFileSync(path.join(root,f),'utf8');
const html=rd('index.html'),config=rd('config.js'),common=rd('scripts/common.js'),home=rd('scripts/home.js'),view=rd('scripts/view.js'),sw=rd('sw.js'),dose=rd('scripts/dose.js'),css=rd('styles/dose.css');

assert.match(html,/name="evrovet-version" content="2\.0\.14"/);
assert.match(common,/appVer:'2\.0\.14'/);
assert.match(html,/styles\/dose\.css\?v=214/);
assert.match(html,/scripts\/dose\.js\?v=214/);
assert.match(config,/dose_calculator:true/);
assert.match(config,/doctor:Object\.freeze\(\[[^\]]*'dose_calculator'/);
assert.match(config,/head:Object\.freeze\(\[[^\]]*'dose_calculator'/);
assert.doesNotMatch((config.match(/assistant_clinical:Object\.freeze\([^\n]+/)||[''])[0],/dose_calculator/);
assert.doesNotMatch((config.match(/assistant_tech:Object\.freeze\([^\n]+/)||[''])[0],/dose_calculator/);
assert.match(home,/dose_calculator:\{[^\n]+view:'dose'/);
assert.match(view,/v==='dose'\)doseOpen\(\)/);
assert.match(view,/S\.view==='dose'\)html=doseHtml\(\)/);
assert.match(view,/\[[^\]]*'dose'[^\]]*\]\.includes\(S\.view\)\)barHtml=navHtml\(\)/);
assert.match(sw,/const V='ev2-shell-29'/);
assert.match(sw,/"styles\/dose\.css"/);
assert.match(sw,/"scripts\/dose\.js"/);
assert.doesNotMatch(sw,/data\/dose-(?:v1|rules-v1)\.json/,'clinical data stays lazy-loaded');
assert.doesNotMatch(dose,/ПИЛОТ|Пилотный|тестовом устройстве/);
assert.match(dose,/Препараты и расчёт дозы/);
assert.match(dose,/status:'all'/,'all 107 items must be the production default');
assert.match(dose,/Весь справочник · 107/);
assert.match(dose,/dose-search-back/);
assert.match(dose,/function doseCmp\(/,'dose range uses exact decimal comparison');
assert.doesNotMatch(dose,/const d=Number\(doseChosenDose/,'comma decimal must not pass through Number');
assert.match(dose,/К результатам поиска/,'return to results is explicit');
assert.match(dose,/history\.pushState\(\{evrovet:evNavSnapshot\(\),dose:/,'drug card participates in browser history');
assert.match(dose,/Критически важно перед расчётом/,'high-risk warning is visible outside details');
assert.match(dose,/разделите минимум на/,'per-site overflow is explicit');
assert.match(dose,/const next=box\.firstElementChild;root\.replaceWith\(next\)/,'scroll target must survive replaceWith');
assert.match(dose,/Правило быстрого расчёта пока не подготовлено/,'missing rule has an exact reason');
assert.match(dose,/'ondansetron':'ондансетрон'/,'agreed Latin aliases are explicit');
assert.match(css,/body\.ui2 \.dose-filter-scroll \.chip\{min-height:44px\}/,'chip target wins the shared CSS cascade');
assert.match(css,/\.dose-immediate-warning\.high\{border-color:#c43a2b;background:#fff0ed/,'high-risk warning has a distinct red accent');
assert.doesNotMatch([html,config,common,home,view,sw,dose].join('\n'),/txcibtcfuzqhhebeguby/,'test project must not leak into live candidate');

const catalog=JSON.parse(rd('data/dose-v1.json')),rules=JSON.parse(rd('data/dose-rules-v1.json'));
assert.equal(catalog.items.length,107);
assert.equal(rules.rules.length,14);
assert.equal(new Set(rules.rules.map(x=>x.item_id)).size,8);
assert.equal(catalog.schema,'evrovet.dose_catalog/v1');
assert.equal(catalog.test_only,false);
assert.equal(rules.schema,'evrovet.dose_rules/v1');
assert.equal(rules.test_only,false);
console.log('dose production catalog 2.0.14 PASS (107 visible by default, 8 calculable, 14 rules, doctor/head only, lazy data)');
